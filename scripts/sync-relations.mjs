#!/usr/bin/env node
// Regenerates src/lib/relationsData.js from
// .claude/skills/greek-market/relations.md. Run manually
// (`node scripts/sync-relations.mjs`) whenever that file changes, and commit
// the output like any other source file.
//
// Parsed at build time rather than read at request time: the dashboard's
// relation map runs on Vercel, whose serverless functions don't reliably
// have arbitrary repo paths outside src/ available at runtime the way a
// plain import does. This also matches how editorial content works in this
// project — hand-authored or generated JS, not a file read live.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(__dirname, "..", ".claude", "skills", "greek-market", "relations.md");
const OUTPUT = join(__dirname, "..", "src", "lib", "relationsData.js");

const SECTION_IDS = {
  Energy: "energy",
  Telecom: "telecom",
  Finance: "finance",
};

const EDGE_RE = /`([^`]+?)\s+--((?:(?!-->).)+)-->\s+([^`]+?)`/gu;
const WHY_RE = /\*\*Why it matters\.\*\*\s*([\s\S]*?)(?:\n\n|$)/u;

function parseEdges(block) {
  const edges = [];
  for (const m of block.matchAll(EDGE_RE)) {
    const subject = m[1].trim();
    const relDetail = m[2].trim();
    const object = m[3].trim();
    const colon = relDetail.indexOf(":");
    const relation = colon === -1 ? relDetail : relDetail.slice(0, colon);
    const detail = colon === -1 ? null : relDetail.slice(colon + 1);
    edges.push({ subject, relation, detail, object });
  }
  return edges;
}

function parseWhy(block) {
  const m = block.match(WHY_RE);
  if (!m) return null;
  return m[1].replace(/\s+/g, " ").trim();
}

function parse(text) {
  const sections = [];

  // Splitting directly on "## " headings rather than the "---" rules between
  // them: the file has one more "---" than there are section boundaries (one
  // trails the last real section, before "## How to extend this file"), so
  // slicing by rule position silently drops sections instead of erroring.
  const sectionSplit = text.split(/^## (.+)$/m).slice(1);
  for (let i = 0; i < sectionSplit.length; i += 2) {
    const title = sectionSplit[i].trim();
    const id = SECTION_IDS[title];
    if (!id) continue; // "How to extend this file" and anything future, unrecognized on purpose
    const sectionBody = sectionSplit[i + 1] || "";

    const entries = [];
    const entrySplit = sectionBody.split(/^### (.+)$/m).slice(1);
    for (let j = 0; j < entrySplit.length; j += 2) {
      const heading = entrySplit[j].trim();
      const entryBody = entrySplit[j + 1] || "";
      entries.push({
        heading,
        why: parseWhy(entryBody),
        edges: parseEdges(entryBody),
      });
    }
    sections.push({ id, label: title, entries });
  }
  return sections;
}

const source = readFileSync(SOURCE, "utf8");
const sections = parse(source);

const totalEdges = sections.reduce(
  (n, s) => n + s.entries.reduce((m, e) => m + e.edges.length, 0),
  0
);

const output = `// AUTO-GENERATED by scripts/sync-relations.mjs from
// .claude/skills/greek-market/relations.md — do not hand-edit.
// Re-run \`node scripts/sync-relations.mjs\` after changing that file.

export const RELATION_SECTIONS = ${JSON.stringify(sections, null, 2)};

export const RELATION_EDGES = RELATION_SECTIONS.flatMap((s) =>
  s.entries.flatMap((e) =>
    e.edges.map((edge) => ({ ...edge, section: s.id, heading: e.heading, why: e.why }))
  )
);
`;

writeFileSync(OUTPUT, output);
console.log(
  `Wrote ${OUTPUT} — ${sections.length} sections, ${totalEdges} edges.`
);
